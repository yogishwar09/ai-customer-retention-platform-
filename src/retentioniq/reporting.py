"""Markdown evaluation report and model card generated from training output."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from retentioniq import config


def _pct(v: float) -> str:
    return f"{v:.1%}"


def evaluation_markdown(meta: dict[str, Any], ev: dict[str, Any]) -> str:
    t = ev["test"]
    at = t["at_threshold"]
    lines = [
        f"# Evaluation report - `{meta['model_version']}`",
        "",
        f"Generated by `make train` on {meta['trained_at']}. All numbers below are computed "
        "on the held-out test split, which was not used for model or threshold selection.",
        "",
        "## Data and split",
        "",
        f"- Dataset fingerprint (SHA-256): `{meta['training_data_fingerprint'][:16]}…`",
        f"- Labelled rows: {meta['training_rows']:,}; churn prevalence {_pct(meta['class_prevalence'])}",
        f"- Split: {meta['split']['method']} (seed {meta['split']['seed']}) - train "
        f"{meta['split']['train']:,} / validation {meta['split']['validation']:,} / test {meta['split']['test']:,}",
        f"- Label definition: {meta['label_definition']}",
        "",
        "## Model comparison (selection on validation PR-AUC)",
        "",
        "| Algorithm | CV PR-AUC (train) | Val PR-AUC | Val ROC-AUC | Val Brier | Selected |",
        "|---|---|---|---|---|---|",
    ]
    for r in ev["comparison"]:
        lines.append(
            f"| {r['algorithm']} | {r['cv_pr_auc_mean']:.3f} ± {r['cv_pr_auc_std']:.3f} | "
            f"{r['val_pr_auc']:.3f} | {r['val_roc_auc']:.3f} | {r['val_brier']:.3f} | "
            f"{'✔' if r['selected'] else ''} |")
    lines += [
        "",
        "## Held-out test performance",
        "",
        "| Metric | Value | 95% bootstrap CI |",
        "|---|---|---|",
        f"| ROC-AUC | {t['roc_auc']:.3f} | {t['ci_95']['roc_auc'][0]:.3f} - {t['ci_95']['roc_auc'][1]:.3f} |",
        f"| PR-AUC | {t['pr_auc']:.3f} | {t['ci_95']['pr_auc'][0]:.3f} - {t['ci_95']['pr_auc'][1]:.3f} |",
        f"| Brier score | {t['brier']:.3f} | |",
        f"| Precision @ threshold {at['threshold']:.2f} | {at['precision']:.3f} | |",
        f"| Recall @ threshold {at['threshold']:.2f} | {at['recall']:.3f} | |",
        f"| Accuracy @ threshold {at['threshold']:.2f} | {at['accuracy']:.3f} | |",
        f"| Accuracy @ 0.50 (for comparison) | {t['at_0_5']['accuracy']:.3f} | |",
        "",
        "Precision among the top-K highest-risk test customers: "
        + ", ".join(f"K={k}: {v:.2f}" for k, v in t["precision_at_k"].items()),
        "",
        "## Subgroup checks (test set)",
        "",
        "| Attribute | Group | n | Prevalence | ROC-AUC | Recall | Flagged share |",
        "|---|---|---|---|---|---|---|",
    ]
    def fmt(row: dict[str, Any], key: str) -> str:
        return f"{row[key]:.3f}" if row.get(key) is not None else "n/a"

    for r in ev["subgroups"]:
        lines.append(f"| {r['attribute']} | {r['group']} | {r['n']} | {fmt(r, 'prevalence')} | "
                     f"{fmt(r, 'roc_auc')} | {fmt(r, 'recall')} | {fmt(r, 'flagged_share')} |")
    lines += ["", "## Release gate", ""]
    for name, (value, limit, ok) in meta["release_gate"]["checks"].items():
        lines.append(f"- {'PASS' if ok else 'FAIL'} - {name}: {value:.3f} (limit {limit})")
    return "\n".join(lines) + "\n"


def model_card_markdown(meta: dict[str, Any], ev: dict[str, Any]) -> str:
    t = ev["test"]
    fb = meta.get("feedback") or {}
    feedback_section = "" if not fb.get("rows_used") else (
        f"\n## Feedback data\n{fb['rows_used']:,} labelled production records from tenant `{fb['org_id']}` were "
        f"added to training ({fb['rows_excluded_test_overlap']:,} excluded for overlapping the test set).")
    top = ", ".join(g["label"] for g in ev["global_importance"][:5])
    return f"""# Model card - `{meta['model_version']}`

## Intended use
Rank existing telecom subscribers by **estimated churn risk** so a retention team can
prioritise *advisory* outreach. Scores support a human decision; they do not decide.

## Out-of-scope / prohibited use
- Denying service, raising prices, or any punitive treatment based on a score.
- Use on populations or products materially different from the training data
  (non-telecom, different market) without re-validation.
- Treating feature contributions as causal reasons why a customer will leave.

## Model
- Algorithm: **{meta['algorithm']}** inside a scikit-learn `Pipeline` (shared preprocessing).
- Operating threshold: **{meta['operating_threshold']:.2f}**, chosen on validation data by
  minimising expected cost with FN:FP = {meta['cost_assumptions']['false_negative']}:{meta['cost_assumptions']['false_positive']}.
- Explanation method: {meta['explanation_method']}.
- Schema version: {meta['schema_version']}; trained {meta['trained_at']}.

## Training data
IBM Telco Customer Churn sample ({meta['training_rows']:,} customers, churn prevalence
{_pct(meta['class_prevalence'])}). {meta['label_definition']}

## Performance (held-out test set, n={meta['split']['test']:,})
- ROC-AUC {t['roc_auc']:.3f} (95% CI {t['ci_95']['roc_auc'][0]:.3f}-{t['ci_95']['roc_auc'][1]:.3f})
- PR-AUC {t['pr_auc']:.3f} (95% CI {t['ci_95']['pr_auc'][0]:.3f}-{t['ci_95']['pr_auc'][1]:.3f}); baseline (random) = prevalence {_pct(t['prevalence'])}
- Brier score {t['brier']:.3f}
- At the operating threshold: precision {t['at_threshold']['precision']:.3f}, recall {t['at_threshold']['recall']:.3f}

Most influential inputs (mean |contribution|): {top}.

## Fairness & limitations
- Subgroup metrics for gender and senior-citizen status are reported in
  `reports/evaluation_report.md`; differences should be reviewed before deployment.
  `gender` is kept as an input only to enable this audit; consider removing it for targeting.
- Snapshot data without timestamps: no time-based validation, so real-world performance
  may be lower than reported.
- No intervention data exists: the model predicts churn, it does not estimate which
  action would prevent it. Expected-value figures in the app use assumed effectiveness.

## Release decision
Release gate {'**passed**' if meta['release_gate']['passed'] else '**failed**'} →
registered as `{meta['status_at_registration']}`. Promotion beyond `candidate` requires an
admin approval recorded in the model registry.
{feedback_section}
"""


def write_reports(meta: dict[str, Any], ev: dict[str, Any], target: Path | None = None) -> list[Path]:
    target = target or config.REPORTS_DIR
    target.mkdir(parents=True, exist_ok=True)
    eval_path = target / "evaluation_report.md"
    card_path = target / "model_card.md"
    eval_path.write_text(evaluation_markdown(meta, ev), encoding="utf-8")
    card_path.write_text(model_card_markdown(meta, ev), encoding="utf-8")
    return [eval_path, card_path]


def publish(version: str) -> None:
    """Copy a version's reports to the top-level reports/ folder (on promotion)."""
    import shutil
    src = config.MODELS_DIR / version
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("evaluation_report.md", "model_card.md"):
        if (src / name).exists():
            shutil.copyfile(src / name, config.REPORTS_DIR / name)
